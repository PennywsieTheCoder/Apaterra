export function mapSupabaseOrder(order) {
  return {
    id: order.id,
    reference: order.reference,
    customer: [order.customer_first_name, order.customer_last_name].filter(Boolean).join(' '),
    email: order.customer_email,
    phone: order.customer_phone,
    city: [order.city, order.region].filter(Boolean).join(', '),
    region: order.region,
    address: order.address,
    landmark: order.landmark,
    notes: order.notes,
    deliveryFee: Number(order.delivery_fee || 0),
    deliveryWindow: order.delivery_window,
    deliveryRider: order.delivery_rider || '',
    riderAssignedAt: order.rider_assigned_at || null,
    dispatchedAt: order.dispatched_at || null,
    deliveredAt: order.delivered_at || null,
    date: order.created_at,
    timeLabel: new Date(order.created_at).toLocaleDateString('en-GH', {
      month: 'short',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    }),
    status: order.status,
    paymentMethod: order.payment_method,
    subtotal: Number(order.subtotal),
    items: (order.order_items || []).map((item) => ({
      id: item.product_id,
      name: item.name,
      type: item.type,
      size: item.size,
      image: item.image_url,
      cardColor: item.card_color,
      price: Number(item.price),
      quantity: item.quantity,
    })),
  }
}
